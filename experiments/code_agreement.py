#!/usr/bin/env python
"""Pillar A — reliability for the data-readiness coding.

Two modes:

  (default) INTER-rater: machine coding
      (experiments/results/taxonomy_sample_machine_labels.csv)
    vs an independent human coding of the same seeded 30-incident sample
      (experiments/results/taxonomy_sample_human_labels.csv)
    -> percent agreement + Cohen's kappa for (a) assigned mode and
       (b) pre-training detectability, plus filter precision (fraction the human
       judged to be a genuine data-readiness failure, i.e. not "other").
    Output: experiments/results/taxonomy_agreement.txt

  --intra  INTRA-rater: the SAME human coder's pass 1
      (experiments/results/taxonomy_sample_human_labels.csv)
    vs a blind pass 2 produced after a washout period
      (experiments/results/taxonomy_sample_human_labels_pass2.csv)
    -> percent agreement + Cohen's kappa for mode and detectability (coding
       stability). Writes a SEPARATE file and never overwrites the inter-rater
       result.
    Output: experiments/results/taxonomy_agreement_intra.txt

Human CSV schema (both passes):
    columns: incident_id,mode,detectability
`mode` in: structural_schema, completeness, distributional, label,
provenance_documentation, cross_source, other.
`detectability` in: yes, partial, no.

The blind pass-2 worksheet is generated by experiments/make_pass2_worksheet.py.

Nothing is fabricated: if a required file is absent, the script prints guidance
and exits 0. Stats appear only once real labels are present.

Reproduce:
    .venv/Scripts/python.exe experiments/code_agreement.py           # inter-rater
    .venv/Scripts/python.exe experiments/code_agreement.py --intra    # intra-rater
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "experiments" / "results"
KEY = RESULTS / "taxonomy_sample_machine_labels.csv"
HUMAN = RESULTS / "taxonomy_sample_human_labels.csv"
HUMAN2 = RESULTS / "taxonomy_sample_human_labels_pass2.csv"
OUT = RESULTS / "taxonomy_agreement.txt"
OUT_INTRA = RESULTS / "taxonomy_agreement_intra.txt"


def cohen_kappa(a: list[str], b: list[str]) -> tuple[float, float]:
    """Return (observed_agreement, cohen_kappa) for two aligned label lists."""
    n = len(a)
    assert n == len(b) and n > 0
    labels = sorted(set(a) | set(b))
    po = sum(1 for x, y in zip(a, b) if x == y) / n
    pe = 0.0
    for lab in labels:
        pa = sum(1 for x in a if x == lab) / n
        pb = sum(1 for x in b if x == lab) / n
        pe += pa * pb
    kappa = (po - pe) / (1 - pe) if (1 - pe) > 1e-12 else float("nan")
    return po, kappa


def confusion(a: list[str], b: list[str], aname: str, bname: str) -> str:
    df = pd.crosstab(pd.Series(a, name=aname), pd.Series(b, name=bname))
    return df.to_string()


def _load(path: Path, lower: bool) -> pd.DataFrame:
    df = pd.read_csv(path).set_index("incident_id")
    return df


def run_inter() -> int:
    if not HUMAN.exists():
        RESULTS.mkdir(parents=True, exist_ok=True)
        key = pd.read_csv(KEY)
        tmpl = key[["incident_id"]].copy()
        tmpl["mode"] = ""
        tmpl["detectability"] = ""
        tmpl_path = RESULTS / "taxonomy_sample_human_labels.TEMPLATE.csv"
        tmpl.to_csv(tmpl_path, index=False)
        print(
            "No human labels yet.\n"
            f"  Fill docs/taxonomy_sample_for_human_review.md, then transcribe to:\n"
            f"    {HUMAN}\n"
            f"  A blank template was written to:\n    {tmpl_path}\n"
            "  Re-run this script afterwards to compute agreement."
        )
        return 0

    key = _load(KEY, lower=False)
    hum = _load(HUMAN, lower=True)
    common = sorted(set(key.index) & set(hum.index))
    if not common:
        print("ERROR: no overlapping incident_id between machine key and human labels.")
        return 1

    m_mode = [str(key.loc[i, "mode"]).strip() for i in common]
    h_mode = [str(hum.loc[i, "mode"]).strip().lower() for i in common]
    m_det = [str(key.loc[i, "detectability"]).strip() for i in common]
    h_det = [str(hum.loc[i, "detectability"]).strip().lower() for i in common]

    po_mode, k_mode = cohen_kappa(m_mode, h_mode)
    po_det, k_det = cohen_kappa(m_det, h_det)
    n_other = sum(1 for x in h_mode if x == "other")
    filter_precision = 1 - n_other / len(common)

    lines = [
        "# Pillar A inter-rater reliability",
        f"n (sampled & double-coded): {len(common)}",
        "",
        "## Assigned mode",
        f"  percent agreement: {po_mode:.3f}",
        f"  Cohen's kappa:     {k_mode:.3f}",
        "",
        "## Pre-training detectability",
        f"  percent agreement: {po_det:.3f}",
        f"  Cohen's kappa:     {k_det:.3f}",
        "",
        "## Filter precision (human judged sampled incident IS data-readiness)",
        f"  human 'other' count: {n_other} / {len(common)}",
        f"  filter precision:    {filter_precision:.3f}",
        "",
        "## Mode confusion (rows=machine, cols=human)",
        confusion(m_mode, h_mode, "machine", "human"),
        "",
        "## Detectability confusion (rows=machine, cols=human)",
        confusion(m_det, h_det, "machine", "human"),
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwrote {OUT}")
    return 0


def run_intra() -> int:
    missing = [p for p in (HUMAN, HUMAN2) if not p.exists()]
    if missing:
        print(
            "Intra-rater pass needs both coding passes present:\n"
            f"    pass 1: {HUMAN}  {'(missing)' if not HUMAN.exists() else 'ok'}\n"
            f"    pass 2: {HUMAN2}  {'(missing)' if not HUMAN2.exists() else 'ok'}\n"
            "  1. Generate the blind worksheet:\n"
            "       .venv/Scripts/python.exe experiments/make_pass2_worksheet.py\n"
            "  2. After a washout period, code docs/taxonomy_sample_pass2_blind.md\n"
            "     WITHOUT looking at pass 1, then transcribe to the pass-2 CSV above\n"
            "     (columns: incident_id,mode,detectability).\n"
            "  3. Re-run with --intra. Nothing is computed until pass 2 exists."
        )
        return 0

    p1 = _load(HUMAN, lower=True)
    p2 = _load(HUMAN2, lower=True)
    common = sorted(set(p1.index) & set(p2.index))
    if not common:
        print("ERROR: no overlapping incident_id between pass 1 and pass 2.")
        return 1
    only1 = sorted(set(p1.index) - set(p2.index))
    only2 = sorted(set(p2.index) - set(p1.index))

    a_mode = [str(p1.loc[i, "mode"]).strip().lower() for i in common]
    b_mode = [str(p2.loc[i, "mode"]).strip().lower() for i in common]
    a_det = [str(p1.loc[i, "detectability"]).strip().lower() for i in common]
    b_det = [str(p2.loc[i, "detectability"]).strip().lower() for i in common]

    po_mode, k_mode = cohen_kappa(a_mode, b_mode)
    po_det, k_det = cohen_kappa(a_det, b_det)

    lines = [
        "# Pillar A intra-rater reliability (coding stability; same coder, two passes)",
        f"n (coded in both passes): {len(common)}",
    ]
    if only1 or only2:
        lines.append(f"  NOTE: incident_ids only in pass1={only1}, only in pass2={only2}")
    lines += [
        "",
        "## Assigned mode",
        f"  percent agreement: {po_mode:.3f}",
        f"  Cohen's kappa:     {k_mode:.3f}",
        "",
        "## Pre-training detectability",
        f"  percent agreement: {po_det:.3f}",
        f"  Cohen's kappa:     {k_det:.3f}",
        "",
        "## Mode confusion (rows=pass1, cols=pass2)",
        confusion(a_mode, b_mode, "pass1", "pass2"),
        "",
        "## Detectability confusion (rows=pass1, cols=pass2)",
        confusion(a_det, b_det, "pass1", "pass2"),
        "",
    ]
    OUT_INTRA.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwrote {OUT_INTRA}  (inter-rater file {OUT.name} untouched)")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--intra", action="store_true",
                    help="intra-rater pass (pass1 vs pass2) instead of machine-vs-human")
    args = ap.parse_args(argv)
    return run_intra() if args.intra else run_inter()


if __name__ == "__main__":
    raise SystemExit(main())
